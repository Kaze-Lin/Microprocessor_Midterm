import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const files = (await readdir(`${root}content`)).filter(f => /^ch\d+\.json$/.test(f)).sort();
const chapters = await Promise.all(files.map(f => readFile(`${root}content/${f}`, 'utf8').then(JSON.parse)));
const ids = new Set();
for (const ch of chapters) {
  if (ids.has(ch.id)) throw new Error(`Duplicate chapter ${ch.id}`);
  ids.add(ch.id);
  if (!ch.sections.length || !ch.checks.length) throw new Error(`Empty chapter ${ch.id}`);
  for (const section of ch.sections) {
    if (ids.has(section.id)) throw new Error(`Duplicate section ${section.id}`);
    ids.add(section.id);
    for (const field of ['level', 'importance', 'connectionLevel']) {
      if (![1,2,3].includes(section[field])) throw new Error(`${section.id}: invalid ${field}`);
    }
    if (section.questions.length < 2 || section.questions.length > 5) throw new Error(`${section.id}: question count`);
    if (!section.sourceRefs.length) throw new Error(`${section.id}: missing sources`);
    for (const q of section.questions) if (![1,2,3].includes(q.level) || !q.answer) throw new Error(`${section.id}: invalid question`);
  }
}
const sources = [...new Map(chapters.flatMap(ch => ch.sources).map(s => [s.file, s])).values()];
for (const ch of chapters) for (const s of ch.sections) {
  for (const ref of s.sourceRefs) {
    const source = sources.find(item => item.file === ref.file);
    if (!source) throw new Error(`Unknown source: ${ref.file}`);
    await readFile(new URL(`../../${ref.file}`, import.meta.url));
    const pages = ref.pages.match(/\d+/g)?.map(Number) ?? [];
    if (!pages.length || pages.some(p => p < 1 || p > source.pages)) throw new Error(`${s.id}: invalid source page`);
  }
  for (const c of s.connections) if (c.target && !ids.has(c.target)) throw new Error(`${s.id}: unknown connection ${c.target}`);
}
const data = { chapters, sources };
await writeFile(`${root}content.js`, `// Generated by scripts/build-content.mjs. Edit content/ch*.json instead.\nwindow.MIDTERM_CONTENT = ${JSON.stringify(data, null, 2)};\n`);
const sections = chapters.flatMap(ch => ch.sections);
console.log(`Content verified: ${chapters.length} chapters, ${sections.length} sections, ${sections.reduce((n,s)=>n+s.questions.length,0)} questions, ${sources.length} PDFs.`);
